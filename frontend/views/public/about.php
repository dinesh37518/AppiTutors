                </li>
                <li>
                    <strong>Academic & Degree Verification</strong>:
                    Inspection of university degrees, PGCE certificates, QTS (Qualified Teacher Status), or subject-specific academic accolades.
                </li>
                <li>
                    <strong>Enhanced DBS Background Check</strong>:
                    Verification of clear criminal record checks against the Children's Barred List.
                </li>
                <li>
                    <strong>Platform Manager Final Approval Gate</strong>:
